"""Shared enums and id helpers for the Benchbook schemas (PDF v0.4).

Id namespaces
- Canonical case items (on disk): local ids F<n>, C<n>, O<n>, flip<n>, noflip<n>, watch<n> inside a case whose
  id is DR-<family>@v<k> (DATA-PIPELINE-DESIGN-v1 §5). Global id = "<case id>/<local id>".
- Served case items (what the agent sees): "<prefix>-<local>", prefix REF1, REF2... in serving order.
  The renumbering table is kept with the served view so scorers can translate back.
- Live items (generated by the agent, or in a gold answer key): LIVE-F<n>, LIVE-O<n>, LIVE-C<n>, LIVE-flip<n>...
"""
from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, ConfigDict

FactKind = Literal["situation", "capability", "authority", "intelligence"]
FactStatus = Literal["confirmed", "assessed"]
# PDF shows strong | weak. `bar` (a consideration that rules options out) exists in the v2.6 cards; kept so
# converted cases lose nothing. Flagged for Peter.
Weight = Literal["strong", "weak", "bar"]
FrameCompare = Literal["same", "same_kind", "different"]
Relation = Literal["follows", "flips", "distinguished", "not_governed"]
Move = Literal["act", "partial", "ask", "refuse", "hold"]
AgentRole = Literal["decide", "execute", "advise"]
Basis = Literal["recommended", "settled", "contested"]

LOCAL_ID = re.compile(r"^(F|C|O|flip|noflip|watch)\d+$")
CASE_ID = re.compile(r"^DR-[A-Za-z0-9-]+@v\d+$")
SERVED_PREFIX = re.compile(r"^REF\d+$")
PROSE_REF = re.compile(r"\{((?:F|C|O|flip|noflip|watch)\d+)\}")   # {O2} in canonical prose -> REF1-O2 when served


class Strict(BaseModel):
    """Strict model: unknown keys are errors (the schema validator's 0/1)."""
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


class Loose(BaseModel):
    model_config = ConfigDict(extra="allow", populate_by_name=True)


def local_kind(local_id: str) -> str:
    m = LOCAL_ID.match(local_id)
    if not m:
        raise ValueError(f"`{local_id}` is not a local case item id (F1, C1, O1, flip1, noflip1, watch1)")
    return m.group(1)
