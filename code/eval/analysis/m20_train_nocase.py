"""M20 (2026-11-15, Peter): memorization check. Does the gen1 SFT adapter answer its TRAINING scenarios without a case
better than it answers unseen (val) scenarios without a case?

No-case choice accuracy (allpairs-scoring-v4, key = X1's gold), base Granite vs the final gen1 adapter:
  train  results/pairs-v1/eval-train-nocase/{base,sft-final}-v4B   438 train X1s, k = 2 (control only)
  val    results/pairs-v1/eval-val/{base,sft-final}-v4B            61 val X1s, k = 4 (control rows of M17)
X1-averaged, 95% family bootstrap (B = 2000). Gain = sft - base per X1. "Gain gap" = train gain - val gain, with a
bootstrap over train families and val families independently (the splits share no family).

Also: train gain by how many SFT rows the X1 had (2-9; dose-response: memorization should grow with exposure), and
per-X1 transitions (base right/wrong -> sft right/wrong).

    PYTHONPATH=code .venv/bin/python -m eval.analysis.m20_train_nocase
"""
from __future__ import annotations

import argparse
import json
import random
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean

RUNS = {("train", "base"): "results/pairs-v1/eval-train-nocase/base-v4B",
        ("train", "sft"): "results/pairs-v1/eval-train-nocase/sft-final-v4B",
        ("val", "base"): "results/pairs-v1/eval-val/base-v4B",
        ("val", "sft"): "results/pairs-v1/eval-val/sft-final-v4B"}


def load():
    """per[(split, model)][x1] = list of 0/1; fam[x1]; meta (no verdict, versions)."""
    per, fam, meta = defaultdict(lambda: defaultdict(list)), {}, {}
    for (split, model), d in RUNS.items():
        nv, n, vers = 0, 0, Counter()
        for line in Path(d, "samples.jsonl").read_text().splitlines():
            s = json.loads(line)
            if s["phase"] != "control":
                continue
            n += 1
            nv += s.get("parsed_choice") is None
            per[(split, model)][s["x1"]].append(float(s.get("translated_choice") is not None
                                                      and s["translated_choice"] == s["gold_choice"]))
            fam[s["x1"]] = s["x1_family"]
            vers[(s.get("scoring") or {}).get("version")] += 1
        meta[f"{split}|{model}"] = {"replies": n, "no_verdict": nv, "scoring": dict(vers)}
    # accuracy among replies with a verdict (separates format fixes from better choices); pooled over replies
    for (split, model), d in RUNS.items():
        ok = [float(s["translated_choice"] == s["gold_choice"]) for s in map(json.loads, Path(d, "samples.jsonl").read_text().splitlines())
              if s["phase"] == "control" and s.get("parsed_choice") is not None]
        meta[f"{split}|{model}"]["acc_with_verdict"] = round(100 * mean(ok), 1)
    return per, fam, meta


def by_family(vals: dict[str, float], fam):
    by = defaultdict(list)
    for x, v in vals.items():
        by[fam[x]].append(v)
    return by


def boot(vals: dict[str, float], fam, B=2000, seed=0):
    by = by_family(vals, fam)
    fams, rng, out = list(by), random.Random(seed), []
    for _ in range(B):
        out.append(mean(v for f in (rng.choice(fams) for _ in fams) for v in by[f]))
    out.sort()
    return mean(vals.values()), out[int(0.025 * B)], out[int(0.975 * B) - 1]


def boot_diff(a: dict, b: dict, fam, B=2000, seed=0):
    """mean(a) - mean(b), a and b on disjoint family sets, resampled independently."""
    ba, bb = by_family(a, fam), by_family(b, fam)
    fa, fb, rng, out = list(ba), list(bb), random.Random(seed), []
    for _ in range(B):
        ma = mean(v for f in (rng.choice(fa) for _ in fa) for v in ba[f])
        mb = mean(v for f in (rng.choice(fb) for _ in fb) for v in bb[f])
        out.append(ma - mb)
    out.sort()
    return mean(a.values()) - mean(b.values()), out[int(0.025 * B)], out[int(0.975 * B) - 1]


def f(t):
    return f"{100 * t[0]:.1f} [{100 * t[1]:.1f}, {100 * t[2]:.1f}]"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/pairs-v1/eval-train-nocase/m20-report.md")
    a = ap.parse_args(argv)
    per, fam, meta = load()
    acc = {k: {x: mean(v) for x, v in d.items()} for k, d in per.items()}
    gain = {sp: {x: acc[(sp, "sft")][x] - acc[(sp, "base")][x] for x in acc[(sp, "base")] if x in acc[(sp, "sft")]}
            for sp in ("train", "val")}
    rows = Counter(json.loads(l)["x1"] for l in Path("results/sft/gen1/sft.jsonl").read_text().splitlines() if l.strip())
    S = {}
    L = ["# M20 tables (generated by `code/eval/analysis/m20_train_nocase.py`)", "",
         "No-case choice accuracy, % (X1-averaged, 95% family bootstrap). Key = X1's gold. Scoring v4.", "",
         "| Split | X1s | families | replies/model | base | SFT final | gain (SFT - base) |", "|---|---|---|---|---|---|---|"]
    for sp in ("train", "val"):
        xs = acc[(sp, "base")]
        b, s_, g = boot(acc[(sp, "base")], fam), boot(acc[(sp, "sft")], fam), boot(gain[sp], fam)
        S[sp] = {"base": b, "sft": s_, "gain": g, "x1s": len(xs), "families": len({fam[x] for x in xs})}
        L.append(f"| {sp} | {len(xs)} | {S[sp]['families']} | {meta[sp + '|base']['replies']} | {f(b)} | {f(s_)} | {f(g)} |")
    gg = boot_diff(gain["train"], gain["val"], fam)
    sg = boot_diff(acc[("train", "sft")], acc[("val", "sft")], fam)
    bg = boot_diff(acc[("train", "base")], acc[("val", "base")], fam)
    S["gain_gap"], S["sft_gap"], S["base_gap"] = gg, sg, bg
    L += ["", f"Gain gap (train gain - val gain): {f(gg)}", f"SFT train - val: {f(sg)}; base train - val: {f(bg)}", ""]
    # dose-response
    L += ["## Train gain by SFT rows per X1", "", "| rows in SFT | X1s | base | SFT final | gain |", "|---|---|---|---|---|"]
    S["dose"] = {}
    for lo, hi in ((2, 3), (4, 5), (6, 7), (8, 9)):
        xs = [x for x in gain["train"] if lo <= rows.get(x, 0) <= hi]
        if not xs:
            continue
        sub = lambda d: {x: d[x] for x in xs}  # noqa: E731
        b, s_, g = boot(sub(acc[("train", "base")]), fam), boot(sub(acc[("train", "sft")]), fam), boot(sub(gain["train"]), fam)
        S["dose"][f"{lo}-{hi}"] = {"x1s": len(xs), "base": b, "sft": s_, "gain": g}
        L.append(f"| {lo}-{hi} | {len(xs)} | {f(b)} | {f(s_)} | {f(g)} |")
    missing = [x for x in gain["train"] if x not in rows]
    L += ["", f"Train X1s with no SFT row: {len(missing)}", ""]
    # transitions on X1 means (both replies right = 1, one = 0.5, none = 0)
    L += ["## Per-X1 transitions (mean of the X1's replies; train k = 2, val k = 4)", "",
          "| Split | base all wrong -> SFT all right | base all right -> SFT all wrong | SFT better | SFT worse | same |",
          "|---|---|---|---|---|---|"]
    for sp in ("train", "val"):
        xs = list(gain[sp])
        up_full = sum(acc[(sp, "base")][x] == 0 and acc[(sp, "sft")][x] == 1 for x in xs)
        down_full = sum(acc[(sp, "base")][x] == 1 and acc[(sp, "sft")][x] == 0 for x in xs)
        up, down = sum(gain[sp][x] > 0 for x in xs), sum(gain[sp][x] < 0 for x in xs)
        S[sp]["transitions"] = {"up_full": up_full, "down_full": down_full, "up": up, "down": down, "same": len(xs) - up - down}
        L.append(f"| {sp} | {up_full} | {down_full} | {up} | {down} | {len(xs) - up - down} |")
    L += ["", "## Runs", ""] + [f"- {k}: {v}" for k, v in meta.items()]
    md = "\n".join(L) + "\n"
    Path(a.out).write_text(md)
    Path(a.out).with_suffix(".json").write_text(json.dumps({"stats": S, "meta": meta}, indent=1))
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
