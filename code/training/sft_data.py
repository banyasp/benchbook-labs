"""SFT examples with loss masks (PDF pp. 19-20, Fig. 5).

Loss goes ONLY on the tokens the model generates as its analogical reasoning (the golden reply and the end-of-turn
token). Everything the harness puts in front of the model is masked (-100): system prompt, the trace, the equities,
the case studies, the analogical-reasoning prompt and any assistant prefill (mode C's `<think>\\nkind: ...`). The
prompt is the harness's rendered `Episode.prompt_text` (chat template already applied, generation prompt included),
so training sees exactly the tokens vLLM sees at inference.

Golden replies are future data: generated by the base model through the harness and kept only if they pass the
format verifier (`ParsedReply.strict_ok`). They carry no authorship rule beyond that; whoever produces training
data must respect the allowlist in config/models.yaml (this module does not write any training data itself).

Golden record (JSONL, one per line):
    {"id": "...", "prompt_text": "<rendered prompt>", "completion": "<generated text, prefill excluded>",
     "prefill": "<assistant prefill that is already inside prompt_text, may be ''>", "meta": {...}}
Build from a harness run:  golden_record(ep, out) -> dict.

    PYTHONPATH=code python -m training.sft_data golden.jsonl out.jsonl --tokenizer ibm-granite/granite-4.2-8b --max-length 20000
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

from bench.schema import parse_reply

IGNORE = -100


@dataclass
class SFTExample:
    input_ids: list[int]
    labels: list[int]
    n_prompt: int
    n_completion: int
    meta: dict = field(default_factory=dict)

    @property
    def attention_mask(self):
        return [1] * len(self.input_ids)

    def as_row(self) -> dict:
        return {"input_ids": self.input_ids, "attention_mask": self.attention_mask, "labels": self.labels}


def golden_record(ep, out, id_: str | None = None, meta: dict | None = None) -> dict:
    """A golden record from a harness Episode and its Completion (generated text = raw_text minus the prefill)."""
    prefill = getattr(ep, "prefill", "") or ""
    raw = out.raw_text
    return {"id": id_, "prompt_text": ep.prompt_text, "prefill": prefill,
            "completion": raw[len(prefill):] if prefill and raw.startswith(prefill) else raw, "meta": meta or {}}


def verify(rec: dict) -> tuple[bool, str]:
    """The format verifier: the whole assistant text (prefill + completion) must parse strictly."""
    p = parse_reply((rec.get("prefill") or "") + rec["completion"],
                    noref=(rec.get("meta") or {}).get("arm") == "none")
    if p.strict_ok:
        return True, "ok"
    why = []
    if p.missing:
        why.append(f"missing {p.missing}")
    why += [f"{k}: {v[:80]}" for k, v in p.errors.items() if k in p.required() and k not in p.missing]
    if any(p.repairs.values()):
        why.append("repairs")
    if p.unknown_kinds:
        why.append(f"unknown kinds {p.unknown_kinds}")
    return False, "; ".join(why) or "not strict_ok"


def tokenize_example(tokenizer, prompt_text: str, completion: str, add_eos: bool = True,
                     max_length: int | None = None, meta: dict | None = None) -> SFTExample | None:
    """prompt tokens (labels -100) + completion tokens (+ eos, labelled). None if longer than max_length
    (dropped, never truncated: a truncated reply would teach the model to stop mid-document)."""
    p = tokenizer(prompt_text, add_special_tokens=False)["input_ids"]
    text = completion
    c = tokenizer(text, add_special_tokens=False)["input_ids"]
    if add_eos:
        c = c + [tokenizer.eos_token_id]       # granite: <|im_end|>
    if max_length is not None and len(p) + len(c) > max_length:
        return None
    return SFTExample(input_ids=p + c, labels=[IGNORE] * len(p) + list(c), n_prompt=len(p), n_completion=len(c),
                      meta=meta or {})


def build_examples(records, tokenizer, verify_format: bool = True, max_length: int | None = None):
    """-> (examples, rejects). rejects = [{id, reason}] for failed verification or too-long sequences."""
    ex, rej = [], []
    for r in records:
        if verify_format:
            ok, why = verify(r)
            if not ok:
                rej.append({"id": r.get("id"), "reason": f"format: {why}"})
                continue
        e = tokenize_example(tokenizer, r["prompt_text"], r["completion"], max_length=max_length,
                             meta={"id": r.get("id"), **(r.get("meta") or {})})
        if e is None:
            rej.append({"id": r.get("id"), "reason": f"longer than max_length {max_length}"})
            continue
        ex.append(e)
    return ex, rej


def decode_unmasked(tokenizer, ex: SFTExample) -> str:
    return tokenizer.decode([t for t in ex.labels if t != IGNORE], skip_special_tokens=False)


def decode_masked(tokenizer, ex: SFTExample) -> str:
    return tokenizer.decode([i for i, l in zip(ex.input_ids, ex.labels) if l == IGNORE], skip_special_tokens=False)


def check_example(tokenizer, ex: SFTExample, prompt_text: str, completion: str) -> list[str]:
    """Mask invariants; returns a list of problems (empty = fine)."""
    bad = []
    if len(ex.input_ids) != len(ex.labels):
        bad.append("length mismatch")
    if any(l != IGNORE for l in ex.labels[: ex.n_prompt]):
        bad.append("a prompt token is unmasked")
    if ex.labels[ex.n_prompt:] != ex.input_ids[ex.n_prompt:]:
        bad.append("completion labels differ from input ids")
    if decode_masked(tokenizer, ex) != prompt_text:
        bad.append("masked span does not decode to the prompt")
    if decode_unmasked(tokenizer, ex).removesuffix(tokenizer.eos_token) != completion:
        bad.append("unmasked span does not decode to the completion")
    return bad


def load_jsonl(path) -> list[dict]:
    return [json.loads(l) for l in Path(path).read_text().splitlines() if l.strip()]


def to_hf_dataset(examples: list[SFTExample]):
    from datasets import Dataset
    return Dataset.from_list([e.as_row() for e in examples])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("golden")
    ap.add_argument("out", help="output JSONL of input_ids/attention_mask/labels")
    ap.add_argument("--tokenizer", default="ibm-granite/granite-4.2-8b")
    ap.add_argument("--max-length", type=int, default=20000)
    ap.add_argument("--no-verify", action="store_true")
    a = ap.parse_args(argv)
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(a.tokenizer)
    recs = load_jsonl(a.golden)
    ex, rej = build_examples(recs, tok, not a.no_verify, a.max_length)
    with open(a.out, "w") as f:
        for e in ex:
            f.write(json.dumps({**e.as_row(), "meta": e.meta}) + "\n")
    Path(a.out).with_suffix(".rejects.json").write_text(json.dumps(rej, indent=1))
    print(f"{len(ex)} examples, {len(rej)} rejected -> {a.out}", file=sys.stderr)
    if ex:
        print(f"mean prompt tokens {sum(e.n_prompt for e in ex) / len(ex):.0f}, "
              f"mean trained tokens {sum(e.n_completion for e in ex) / len(ex):.0f}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
